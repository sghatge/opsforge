"""OPSFORGE — SOP draft generator.

Standardization Hub module: produces a human-readable Standard Operating
Procedure draft from a registered process. Template-driven and deterministic
by design; an LLM provider can refine wording in a later release.
"""

from __future__ import annotations

import json

from ..db import Database, new_id, now
from . import processes

_SOP_TEMPLATE = """# Standard Operating Procedure (DRAFT)

## 1. Process
- **Name:** {name}
- **Owner:** {owner}
- **Description:** {description}

## 2. Purpose
This procedure defines how {name} is executed so that outcomes are
consistent, auditable and independent of individual team members.

## 3. Scope
Applies to every execution of {name} within the organisation. Exceptions
require written approval from the process owner.

## 4. Roles and responsibilities
| Role | Responsibility |
| --- | --- |
| Process owner ({owner}) | Accuracy of this SOP and of the process outcome |
| Operator | Executes the steps exactly as documented |
| Reviewer | Verifies outputs and approves exceptions |

## 5. Procedure
1. Confirm the inputs required for {name} are complete and valid.
2. Execute the process steps in the documented order.
3. Record evidence of each completed step.
4. Verify the outcome against the acceptance criteria in section 6.
5. File the result and store the evidence record.

## 6. Acceptance criteria
- All required inputs were present and validated.
- Every step produced stored evidence.
- The outcome meets the agreed quality threshold.

## 7. Escalation
If a step cannot be completed as documented, stop, record the issue and
escalate to the process owner within one working day.

## 8. Review cycle
Review this SOP every quarter and after any material change to the process.

---
*Generated by OPSFORGE {version} — draft for human review.*
"""


def generate_sop(db: Database, process_id: str) -> dict:
    process = processes.get_process(db, process_id)
    body = _SOP_TEMPLATE.format(
        name=process["name"],
        owner=process["owner"] or "Unassigned",
        description=process["description"] or "Not documented yet.",
        version="v0.3",
    )
    db.audit("sop.generated", {"process_id": process_id})
    return {"process_id": process_id, "process_name": process["name"], "sop_markdown": body}


def save_sop_evidence(db: Database, sop: dict) -> dict:
    """Store a generated SOP in the evidence register."""
    return create_evidence(
        db,
        {
            "kind": "sop_draft",
            "ref_id": sop["process_id"],
            "title": f"SOP draft — {sop['process_name']}",
            "payload": sop,
        },
    )


def create_evidence(db: Database, data: dict) -> dict:
    kind = (data.get("kind") or "").strip()
    title = (data.get("title") or "").strip()
    if not kind or not title:
        raise ValueError("Evidence requires 'kind' and 'title'.")
    row = {
        "id": new_id("evd"),
        "kind": kind,
        "ref_id": (data.get("ref_id") or "").strip(),
        "title": title,
        "payload": data.get("payload") or {},
        "created_at": now(),
    }
    db.execute(
        "INSERT INTO evidence (id, kind, ref_id, title, payload, created_at) VALUES (?, ?, ?, ?, ?, ?)",
        (row["id"], kind, row["ref_id"], title, json.dumps(row["payload"]), row["created_at"]),
    )
    db.audit("evidence.created", {"id": row["id"], "kind": kind, "title": title})
    return row


def list_evidence(db: Database) -> list[dict]:
    rows = db.query("SELECT * FROM evidence ORDER BY created_at DESC")
    for r in rows:
        r["payload"] = json.loads(r["payload"])
    return rows
